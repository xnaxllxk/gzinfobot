package main

// Единый интерфейс модуля. Каждая функция бота (курсы, топливо, погода, пользовательские
// источники) описывает себя одинаково: имя, поля настроек, как обновить данные и какой блок
// текста дать в отчёт. Остальной код про конкретные модули ничего не знает.
//
// Как добавить свой модуль:
//  1. создать файл mod_<имя>.go с типом, реализующим Module;
//  2. добавить одну строку в список builtins (registry.go).
// Подробнее — MODULES.md.

import (
	"context"
	"net/http"
	"time"
)

// Block — то, что модуль отдаёт в отчёт. Пустой Text не выводится (но Warn учитывается).
type Block struct {
	Text string   // готовый кусок сообщения
	Warn []string // пометки «внимание» в конце отчёта
}

// Env — всё, что модулю нужно для работы. Модуль не лезёт в глобальные переменные:
// так его легко тестировать и запускать «вхолостую» (/test) на временном хранилище.
type Env struct {
	HC         *http.Client  // клиент для внешних страниц (с защитой от обращений во внутреннюю сеть)
	AI         *aiClient     // ИИ-шлюз: «достань числа из текста»
	St         *store        // хранилище результатов
	Cfg        Cfg           // настройки этого модуля
	Now        time.Time     // «сейчас» (можно подменить в тестах)
	StaleAfter time.Duration // через сколько данные считаются устаревшими
}

func (e *Env) now() time.Time {
	if e.Now.IsZero() {
		return time.Now()
	}
	return e.Now
}

// Module — один подключаемый блок отчёта.
type Module interface {
	// Name — короткий идентификатор: ключ в settings.json, в кэше и в командах (/enable fuel).
	Name() string
	// Title — человеческое название для сообщений админу.
	Title() string
	// Fields — настройки модуля: тип, диапазон, значение по умолчанию. Из них строится
	// проверка в /set и справка в /settings.
	Fields() []Field
	// Refresh получает свежие данные и кладёт их в e.St. Вызывается по расписанию, из /refresh
	// и из /test (там на временное хранилище). Вернуть ошибку = «не получилось».
	Refresh(ctx context.Context, e *Env) error
	// Render строит блок отчёта из того, что лежит в e.St. Не должен ходить в сеть
	// (исключение — погода, у которой своё короткое время жизни кэша).
	Render(ctx context.Context, e *Env) Block
}
